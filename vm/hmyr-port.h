/* 这台机器与「它跑在哪」之间只有两个约定：怎么读一个文件的字节，
 * 怎么把一段字节写出去。其余与语言有关的东西全在 hmyr.c 里。
 *
 * 桌面上的两份实现在 hmyr.c 里，是默认值 —— 不装也能跑。
 * 板子上要装：开机时调一次 hmyr_装平台，把从串口、SD 卡、或者
 * 烧在 Flash 里的那一段字节读出来，再写回串口。
 *
 * 这一份是给移植者看的：它故意只有这么点内容，因为除此之外没有别的约定。 */
#ifndef HMYR_PORT_H
#define HMYR_PORT_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
  /* 读一个文件的字节：成功交回 1 并把指针与长度填好，失败交回 0。
   * 这块内存在这台机器的生命周期里只读，它不会去改。 */
  int (*读)(const char *路径, uint8_t **出, size_t *长);

  /* 写一段字节到标准出口。板子上一般就是串口或 SWO。 */
  void (*写)(const uint8_t *p, size_t n);

  /* 出了要命的事时，把这句话送到能看见的地方。可以不装（那就是 fprintf(stderr)）。
   *
   * 为什么这一条必须存在：这台机器在「分配失败」时唯一能做的就是停下，而停下来
   * 之后什么也没有 —— 板子上没有 stderr，于是「装不下」的表现是串口一片空白。
   * 而空白与「程序根本没跑」看起来一模一样，那正是最费时间的那一种。
   *
   * design/BOARD.txt 第十一节记着这张表：20 块跑通、30 块跑通、40 与 50 块
   * 各自只有几百个零字节。有了这一条，那两格会说清它们为什么没出来。 */
  void (*错误)(const char *p, size_t n);
} Hmyr平台;

/* 装上一次。传 NULL 表示退回桌面那两份实现。 */
void hmyr_装平台(const Hmyr平台 *p);

/* 跑一份字节码。这是给「没有 argv、也没有文件系统」的地方准备的入口 ——
 * 板子上开机会调它一次。路径是平台口「读」的钥匙：板子上那个读忽略它，
 * 桌面上那个读拿它去 fopen。交回退出码。 */
int hmyr_运行(const char *路径, int 参数量, char **参数);

/* 这次运行的堆峰值（字节）。
 *
 * 这个数一直是记录的，与 HMYR_MEM 无关 —— 那个环境变量只决定要不要在退出时
 * 打到 stderr。裸机上没有 stderr，所以要么有这条接口，要么那个数就没人看得见。
 *
 * 为什么它比 HMYR_MEM 的输出可信：诊断自己也在堆上分配。板子上 getenv 返回 0，
 * 诊断开不起来，于是这里读到的数就是程序自己的峰值。 */
size_t hmyr_堆峰值(void);

/* 分配直方图：第 i 档是「大小落在 [i*8, i*8+7] 的分配次数」，共 hmyr_分配档数() 档。
 *
 * 这三条存在的理由是同一个：裸机上没有 stderr，而诊断要能被「读出来」而不是
 * 「打出来」。板侧先 hmyr_开直方() 打开统计，跑完再逐档取走。
 *
 * 平常两个函数都不花一个字节 —— 记直方 那个开关关着时，记一笔 直接返回。 */
size_t hmyr_分配档(int i);
/* 第 i 档的字节总量。最后一档是「184 字节及以上」，而堆的大头常常就落在那里 ——
 * 只给次数时，那一档回答不了「堆被谁吃掉」。 */
size_t hmyr_档字节(int i);
int hmyr_分配档数(void);
void hmyr_开直方(void);

/* 行号证据：第 i 个被记下来的调用点在哪一行（hmyr_分配行）、要了多少次（hmyr_分配行次）。
 *
 * 与上一组的分工：那一组说「哪一档最多」，这一组说「谁在要它」。两者合起来，
 * 「同一个程序在板子上比在宿主机上少一半」这种事才有落点 —— 它不再是「某处不同」，
 * 而是「第 N 行的分配在两边落进了不同的档」。
 *
 * 只在 hmyr_开直方() 之后才有数。 */
unsigned hmyr_分配行(int i);
size_t hmyr_分配行次(int i);
/* 第 i 个行号的字节总量。次数多不等于字节多：次数最多的几行常常是几十字节的小分配，
 * 而堆的大头是少数几次上万字节的分配 —— 两个数并排才找得到它。 */
size_t hmyr_分配行字节(int i);
int hmyr_分配行数(void);

/* GC 块按种类分开：0 值槽、1 字符串、2 索引项、3 索引。hmyr_种次 是「这一类要了几块」，
 * hmyr_种字节 是「一共多少字节」，而 hmyr_种档次(种, 档) 是「这一类有多少块落在哪个尺寸档」
 * （每档 8 字节，24 档）。
 *
 * 第三个数是最后一层证据：只有它能把「种类的数」与「档位的数」对上 ——
 * 「95 个字符串块，而 24 到 31 那一档只有 3 个」这种矛盾，正是在这里解的。 */
size_t hmyr_种次(int i);
size_t hmyr_种字节(int i);
int hmyr_种数(void);
size_t hmyr_种档次(int 种, int 档);

/* 装载分步跟踪：开一次，装载的每一步之后把「到这一步为止的堆峰值」报到平台口。
 * 它是一条接口而不是环境变量，因为板子上 getenv 返回 0 —— 那一条开不起来。
 * 用处：code_at 压成两字节时，32 位桌面省 22802 字节而板子只省 482，
 * 说明两个平台卡的地方不同，而看代码看不出来。 */
void hmyr_开装载跟踪(void);

/* 递归的两条的读数：最深的调用层数，与这一趟递归用掉的栈字节。
 *
 * 为什么要它们（2026-10-30）：六份自举层装得下（峰值 43792），执行时栈溢出 ——
 * 而「溢出」那时候只说明后果，说不清深度与字节数。这两个数在崩溃之前就已经
 * 记在全局里了，板侧在硬错误那一行把它们念出来，就不必再开调试器读 MSP。
 *
 * 栈字节的定义是「最深帧地址减最浅帧地址」：一个 run_func 的帧里那些槽栈与
 * 保存寄存器都算在内，所以它比「层数乘估算值」更接近真实。 */
int hmyr_最深(void);
int hmyr_栈字节(void);

/* 操作数栈的两个数：push 到达过的最深位置，与当前的容量。
 * 两个并排看才知道「那一次扩容是必须的，还是翻倍太粗」。 */
size_t hmyr_操作数峰值(void);
size_t hmyr_操作数容量(void);

/* 帧池的两个数：这一刻的深度与容量。与 操作数栈 那一对同一种用法。 */
size_t hmyr_帧深(void);
size_t hmyr_帧容量(void);

/* 深度阶梯：打开之后，递归每到一个 2 的幂就在平台口打一行 depth=/stack=。
 *
 * 为什么需要它而不是在硬错误里读（2026-10-30 试过）：栈溢出之后处理函数里
 * 每调用一个函数都会再触发一次硬错误 —— 串口上只剩半行被无限重复。
 * 崩溃之前的输出才是安全的证据，所以档位在正常栈上打。 */
void hmyr_开深度档(void);

#endif
