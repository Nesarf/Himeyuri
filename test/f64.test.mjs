// 双精度，用自己的整数算术实现：加、减、乘、比。
//
// 这一套的判据是逐位的：同样的两个数，自己算出来的位模式与宿主算出来的位模式相同。
// 「差不多」在这一层没有意义 —— 差一位就是一个不同的数，而它会在下一次运算里放大。
//
// 三组证据：
//   一、定位值的一批（零、负零、次正规、最大最小正规、无穷、NaN）两两组合。
//   二、一千个位模式两两组合，其中一半是随机位模式，一半落在日常数量级。
//   三、边界那几条单独说：x 加负 x 给正零、溢出、下溢到零、半程取偶、NaN 与无穷相乘。
//
// 随机用固定种子（线性同余）。用 Math.random 的话，失败不可复现，而不可复现的失败
// 最后都变成「刚才还好的」。
import * as f from "../src/f64.mjs";

let passed = 0, failed = 0;
const ok = (label, condition, detail = "") => {
  if (condition) { passed++; console.log("  通过  " + label); }
  else { failed++; console.log("  不通过  " + label + (detail ? "  " + detail : "")); }
};
const 是 = (label, 给, 应) => {
  const 同一 = 一样(给, 应);
  ok(label, 同一, "我给 " + 给 + "，宿主 " + 应);
};

// 两个双精度数是不是同一个数：NaN 对 NaN 也算同一个，负零与正零不算。
const 一样 = (甲, 乙) => {
  if (Number.isNaN(甲) && Number.isNaN(乙)) return true;
  return Object.is(甲, 乙);
};

console.log("一、那二十六个位置：两两组合，加与乘与比");
{
  const 定位 = [
    0, -0, 1, -1, 0.1, 0.2, 0.5, 2, 3, 1e308, -1e308, 5e-324, 2.2250738585072014e-308,
    Infinity, -Infinity, NaN, 1.7976931348623157e308, 9007199254740992, 9007199254740993,
    1 / 3, 1e-7, 123456789012345680000, 0.30000000000000004, 1e-310, -1e-310, 4.9e-324,
  ];
  const 位们 = 定位.map((x) => f.收(x));
  let 坏 = [];
  for (const x of 位们) for (const y of 位们) {
    const a = f.交(x), b = f.交(y);
    if (!一样(f.交(f.加(x, y)), a + b)) 坏.push(a + " + " + b);
    if (!一样(f.交(f.乘(x, y)), a * b)) 坏.push(a + " * " + b);
    const 应 = Number.isNaN(a) || Number.isNaN(b) ? null : (a < b ? -1 : a > b ? 1 : 0);
    if (f.比(x, y) !== 应) 坏.push("比 " + a + " " + b);
    if (!一样(f.交(f.减(x, y)), a - b)) 坏.push(a + " - " + b);
  }
  ok("六百七十六对，一处不差", 坏.length === 0, 坏.slice(0, 4).join(" · "));
}

console.log("二、一千个位模式：随机与日常数量级各一半");
{
  // 固定种子。数值本身不重要，重要的是它对每一次运行都一样。
  let 种 = 20261021;
  const 随 = () => { 种 = (种 * 1103515245 + 12345) % 2147483648; return 种 / 2147483648; };
  const 位们 = [];
  for (let i = 0; i < 400; i++) {
    位们.push((BigInt(Math.floor(随() * 0x100000000)) << 32n) | BigInt(Math.floor(随() * 0x100000000)));
  }
  // 随机位模式多半落在极大或次正规区，而日常的算术发生在中间那几档，所以再补一半。
  for (let i = 0; i < 600; i++) 位们.push(f.收((随() - 0.5) * Math.pow(2, Math.floor(随() * 40) - 20)));

  let 坏 = [], 次数 = 0;
  for (const x of 位们) for (const y of 位们) {
    const a = f.交(x), b = f.交(y);
    次数 += 3;
    if (!一样(f.交(f.加(x, y)), a + b)) 坏.push(a + " + " + b);
    if (!一样(f.交(f.乘(x, y)), a * b)) 坏.push(a + " * " + b);
    const 应 = Number.isNaN(a) || Number.isNaN(b) ? null : (a < b ? -1 : a > b ? 1 : 0);
    if (f.比(x, y) !== 应) 坏.push("比 " + a + " " + b);
  }
  ok("一百万个组合（" + 次数 + " 次对照）没有一处分岔", 坏.length === 0, 坏.slice(0, 4).join(" · "));
}

console.log("三、边界：那些一到就错的地方");
{
  是("一个次正规加它自己，是两倍", f.交(f.加(f.收(5e-324), f.收(5e-324))), 1e-323);
  是("最大正规乘十，溢出成无穷", f.交(f.乘(f.收(1e308), f.收(10))), Infinity);
  是("最小次正规乘零点五，舍到正零", f.交(f.乘(f.收(5e-324), f.收(0.5))), 0);
  ok("而它舍出来的是正零，不是负零", Object.is(f.交(f.乘(f.收(5e-324), f.收(0.5))), 0));

  // x 加负 x：最近偶数下给正零。这一条最容易写成负零。
  ok("一加负一给正零", Object.is(f.交(f.加(f.收(1), f.收(-1))), 0));
  ok("负零加负零给负零", Object.is(f.交(f.加(f.收(-0), f.收(-0))), -0));
  ok("正零加负零给正零", Object.is(f.交(f.加(f.收(0), f.收(-0))), 0));
  ok("负零加正数，给那个正数", Object.is(f.交(f.加(f.收(-0), f.收(3))), 3));

  ok("无穷减无穷是 NaN", Number.isNaN(f.交(f.减(f.收(Infinity), f.收(Infinity)))));
  ok("零乘无穷是 NaN", Number.isNaN(f.交(f.乘(f.收(0), f.收(Infinity)))));
  ok("NaN 加任何东西都是 NaN", Number.isNaN(f.交(f.加(f.收(NaN), f.收(1)))));
  ok("负数乘无穷是负无穷", f.交(f.乘(f.收(-1), f.收(Infinity))) === -Infinity);

  // 半程取偶：2 的 53 次方那一档的 ulp 是二，所以加一正好落在两个候选的中间，
  // 舍到偶数那一个；加三也一样。这两条一起才说明「取偶」不是「总是往下」。
  // 而 2 的 52 次方那一档的 ulp 是一，加一是个精确的数 —— 两条完全不同的事。
  是("2 的 52 次方加一是精确的", f.交(f.加(f.收(4503599627370496), f.收(1))), 4503599627370497);
  是("2 的 53 次方加一是半程，舍到偶数那一头", f.交(f.加(f.收(9007199254740992), f.收(1))), 9007199254740992);
  是("2 的 53 次方加三也是半程，舍到加四", f.交(f.加(f.收(9007199254740992), f.收(3))), 9007199254740996);
  是("0.1 加 0.2 是那个熟悉的偏差", f.交(f.加(f.收(0.1), f.收(0.2))), 0.1 + 0.2);

  // 比较里最容易错的一条：负零不该被当成最小的数。
  ok("负零不小于零", f.比(f.收(-0), f.收(0)) === 0);
  ok("负零不小于一", f.比(f.收(-0), f.收(1)) === -1);
  ok("零小于最小次正规", f.比(f.收(0), f.收(5e-324)) === -1);
  ok("NaN 比不了，交回 null", f.比(f.收(NaN), f.收(1)) === null);
  ok("负无穷小于负的最大正规", f.比(f.收(-Infinity), f.收(-1.7976931348623157e308)) === -1);
}

console.log("四、拆与装：位模式进得去出得来");
{
  const 例 = [0, -0, 1, -1, 0.1, 5e-324, 2.2250738585072014e-308, 1.7976931348623157e308, Infinity, -Infinity];
  let 全对 = true;
  for (const n of 例) {
    const 位 = f.收(n);
    if (!Object.is(f.交(位), n)) { 全对 = false; break; }
  }
  ok("十个位置的位模式往返都是原来那个数", 全对);
  const 拆开 = f.拆(f.收(0.1));
  ok("0.1 拆出来是正规数，隐含位在", 拆开.种 === "有限" && (拆开.M >> 52n) === 1n);
  ok("它的符号是正", 拆开.负 === false);
  const 次 = f.拆(f.收(5e-324));
  ok("最小次正规拆出来是指数为零的那一档", 次.种 === "有限" && 次.M === 1n && 次.E === -1074);
  const 非 = f.拆(f.收(NaN));
  ok("NaN 拆出来是非数，不是有限", 非.种 === "非数");
  ok("负零拆出来是零且带符号", f.拆(f.收(-0)).种 === "零" && f.拆(f.收(-0)).负 === true);
}

