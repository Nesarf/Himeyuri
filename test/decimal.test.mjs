// 十进制往返：把双精度打成最短的串，再从串读回来。
//
// 判据只有一条：串要一字不差，位模式要一位不差。
//
//   一、成文：一千多个值逐字对照宿主的 String()。
//   二、解析：把每个值的串读回来，位模式相同。
//   三、最短：成文的串摘掉最后一位就读不回原值 —— 短一位是假的，长一位是浪费。
//   四、排版：定点与指数形式的分界照 ECMAScript 那一套，而它与宿主的输出一致。
//
// 随机用固定种子。这一层最容易出的是「大部分对、个别差一位」的错，
// 而那种错在随机里出现得比人眼能看见的更频繁。
import { 位 } from "../src/numbers.mjs";
import { 由位 } from "../src/numbers.mjs";
import * as d from "../src/decimal.mjs";

let passed = 0, failed = 0;
const ok = (label, condition, detail = "") => {
  if (condition) { passed++; console.log("  通过  " + label); }
  else { failed++; console.log("  不通过  " + label + (detail ? "  " + detail : "")); }
};

const 定位 = [
  0, -0, 1, -1, 0.1, 0.2, 0.3, 1 / 3, 1e21, 1e-7, 1e-6, 1e20, 1e22, 123456789012345680000,
  9007199254740992, 9007199254740993, 5e-324, 1.7976931348623157e308,
  2.2250738585072014e-308, 1e-310, 0.30000000000000004, 1e308, 100, 0.5, 3.5,
  1234.5678, 1e100, 1e-100, 1.5e-10, 123456789012345678,
];
let 种 = 20261023;
const 随 = () => { 种 = (种 * 1103515245 + 12345) % 2147483648; return 种 / 2147483648; };
const 随值 = [];
for (let i = 0; i < 3000; i++) {
  const b = (BigInt(Math.floor(随() * 0x100000000)) << 32n) | BigInt(Math.floor(随() * 0x100000000));
  随值.push(由位(b));
}
for (let i = 0; i < 2000; i++) 随值.push((随() - 0.5) * Math.pow(10, Math.floor(随() * 40) - 20));
const 全 = [...定位, ...随值];

console.log("一、成文：" + 全.length + " 个值，逐字对照宿主的 String()");
{
  const 坏 = [];
  for (const x of 全) {
    const 得 = d.成文(位(x));
    if (得 !== String(x) && 坏.length < 6) 坏.push(String(x) + " -> " + 得);
  }
  ok("一字不差", 坏.length === 0, 坏.join(" · "));
}

console.log("二、解析：每个串读回同一个位模式");
{
  const 坏 = [];
  let 次数 = 0;
  for (const x of 全) {
    if (Number.isNaN(x) || Object.is(x, -0)) continue;  // 这两个读不回原值，见第三节
    次数++;
    const 得 = d.解析(String(x));
    if (得 !== 位(x) && 坏.length < 6) 坏.push(String(x) + " -> " + 得);
  }
  ok(次数 + " 个串一位不差", 坏.length === 0, 坏.join(" · "));
}

console.log("三、最短：摘掉最后一位就读不回");
{
  // 只要有一个样本「摘一位还能读回」，这一条就说明最短化没做到。
  // 判定办法是从串里拼出少一位的那个数，再看它的位模式是不是变了。
  const 坏 = [];
  for (const x of 定位) {
    if (!Number.isFinite(x) || x === 0) continue;
    const 串 = d.成文(位(x));
    const m = /^([+-]?)(\d+)(?:\.(\d+))?(?:[eE]([+-]?\d+))?$/.exec(串);
    if (!m) continue;
    const 号 = m[1], 整 = m[2] || "", 小 = m[3] || "", 指 = m[4] ? Number(m[4]) : 0;
    let 数字 = BigInt(整 + 小);
    let 指数 = 指 - 小.length;
    if (数字 % 10n === 0n) continue;        // 结尾是零的串本来就能再短一位，那是排版的事
    const 更短 = 数字 / 10n;
    const 位短 = d.装十进制(更短, 指数 + 1, 号 === "-");
    if (位短 === 位(x) && 坏.length < 6) 坏.push(串 + " 摘一位还是原值");
  }
  ok("摘一位一定会变成另一个数（或者那一位本来就不该在）", 坏.length === 0, 坏.join(" · "));
}

console.log("四、排版：定点与指数形式的分界");
{
  const 表 = [
    [1e21, "1e+21"],
    [1e20, "100000000000000000000"],
    [1e-7, "1e-7"],
    [1e-6, "0.000001"],
    [123456789012345680000, "123456789012345680000"],
    [0.30000000000000004, "0.30000000000000004"],
    [1.7976931348623157e308, "1.7976931348623157e+308"],
    [5e-324, "5e-324"],
    [-0, "0"],
  ];
  for (const [值, 应] of 表) ok("成文(" + JSON.stringify(值) + ") 是 " + 应, d.成文(位(值)) === 应, d.成文(位(值)));
}

console.log("五、解析认什么、拒什么");
{
  ok("零位", d.解析("0") === 0n);
  ok("负零位（带符号）", d.解析("-0") === 0x8000000000000000n);
  ok("点在前面的那种写法", d.解析(".5") === 位(0.5));
  ok("点在后头的也算", d.解析("5.") === 位(5));
  ok("带正号的指数", d.解析("1e+3") === 位(1000));
  ok("大写得下去的指数", d.解析("1E3") === 位(1000));
  ok("溢出给无穷", d.解析("1e400") === 位(Infinity));
  ok("下溢给零", d.解析("1e-400") === 0n);
  ok("十六进制不认（那是切词器的事）", d.解析("0x10") === null);
  ok("NaN 这两个字母不认", d.解析("NaN") === null);
  ok("空串不认", d.解析("") === null);
  ok("只有点不认", d.解析(".") === null);
  ok("中间夹字母不认", d.解析("1a2") === null);
}

console.log("");
console.log(passed + " passed, " + failed + " failed");
process.exit(failed === 0 ? 0 : 1);
