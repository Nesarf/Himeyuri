// M4's second acceptance: the description survives a round trip, and a piece can be generated rather
// than transcribed. Both are checked on data, not on prose.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadPiece, validatePiece } from "../kpb/host.mjs";
import { emitPiece } from "../kpb/emit.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
let passed = 0, failed = 0;
const ok = (label, condition, detail = "") => {
  if (condition) { passed++; console.log("  通过  " + label); }
  else { failed++; console.log("  不通过  " + label + (detail ? "  " + detail : "")); }
};

const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);

for (const name of ["piece.hmyr", "etude.hmyr"]) {
  const file = path.join(ROOT, "kpb", name);
  const first = loadPiece(file);
  ok(name + " runs", first.ok, first.ok ? "" : first.diagnostics.items.map((d) => d.code + " " + d.message).join("; "));
  if (!first.ok) continue;
  ok(name + " satisfies the shape", validatePiece(first.data).length === 0, validatePiece(first.data).join("; "));

  // emit it, load what was emitted, and the two values must agree
  const source = emitPiece(first.data);
  const generated = path.join(os.tmpdir(), "hmyr-roundtrip-" + name.replace(/[^a-z]/gi, "") + ".hmyr");
  fs.writeFileSync(generated, source, "utf8");
  const second = loadPiece(generated);
  ok(name + " round-trips through emitted source", second.ok && same(first.data, second.data),
    second.ok ? "the two values differ" : second.diagnostics.items.map((d) => d.code).join(","));
  fs.rmSync(generated, { force: true });
}

// the point of a language over a data format: the notes were built, not typed out
{
  const etude = loadPiece(path.join(ROOT, "kpb/etude.hmyr"));
  const lead = etude.ok ? etude.data.score.tracks.find((t) => t.name === "lead") : null;
  ok("the etude's lead line was generated by recursion", lead && lead.notes.length === 8,
    lead ? String(lead.notes.length) : "no lead track");
  ok("each step is two semitones up and 240 ticks on",
    lead && lead.notes.every((n, i) => n[0] === 60 + i * 2 && n[1] === i * 240 && n[2] === 240));
  const drums = etude.ok ? etude.data.score.tracks.find((t) => t.name === "drums") : null;
  ok("the drum line alternates strong and weak beats",
    drums && drums.notes.every((n, i) => n[0] === (i % 2 === 0 ? 36 : 38)));
  ok("the two pieces differ, so the generator is doing work",
    !same(loadPiece(path.join(ROOT, "kpb/piece.hmyr")).data, etude.data));
}

// emitted source must itself be plain text with no rendering syntax
{
  const source = emitPiece(loadPiece(path.join(ROOT, "kpb/piece.hmyr")).data);
  ok("the emitted source has no rendering syntax", !/\*\*/.test(source) && !/^#/m.test(source) && !/^\|/m.test(source));
  ok("the emitted source is re-readable in one piece", source.split("\n").length > 10 && source.trimEnd().endsWith("}"));
}

console.log("\n" + passed + " passed, " + failed + " failed");
process.exit(failed === 0 ? 0 : 1);
