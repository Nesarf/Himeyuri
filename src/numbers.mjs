// 数：这门语言里「数」的意思，只有一个定义处。
//
// 这一份没有把数换掉。它做的是把数的意思收成一处，好让换掉实现的时候只有一个落点。
//
// 为什么要收：数曾经散在四个地方各自定义 —— 两个切词器把字面量交给 Number()，
// 执行器自己写裸算术，内置表自己写 Math.floor 与 String()。四处一致纯属运气，
// 而运气不会在换实现之后还继续成立。design/SCALARS.txt 那五十三条量出来的行为，
// 就是这一层要保住的东西；test/numbers.test.mjs 把它们跑在三执行路上。
//
// 此刻的位置（2026-10-24）：入口与出口已经换掉了。解析与成文走 src/decimal.mjs，
// 那是自己写的十进制往返，一位不差地对过宿主；进制那一支也自己数。
// 而算术与比较仍是宿主的双精度 —— 加、减、乘、除、余、比、下整这几行还是裸运算。
// 所以 design/VM.txt 的「还没做的」里，标量那一条仍然成立，只是短了一半。
import * as 十进 from "./decimal.mjs";
import { 位, 由位 } from "./bits.mjs";
export { 位, 由位 };

// 一个值是数吗。执行器判断值是什么，问这里，而不是自己写 typeof。
export const 是数 = (v) => typeof v === "number";

// 收一个值进来当数用：数是数，布尔当一用，别的一律不是。
// 交回 null 而不是抛：报哪一个编号是执行器的事，不在这一层编。
export const 收 = (v) => (typeof v === "number" ? v : typeof v === "boolean" ? (v ? 1 : 0) : null);

// 把宿主给的整数收进语言里（长度、计数这类）。它现在就是一个恒等函数，
// 而它存在的理由是：宿主整数进入语言也是一处入口，换实现之后这里要动，
// 那时候场上只该有一个地方等着改。
export const 造 = (n) => n;

// 源码里的字面量 → 数。进制给 0 表示按前缀走（0x / 0b / 0o 由文本自己说），
// 否则按给的进制读那串数字（切词器已经把前缀剥掉了）。
//
// 十进制那一支现在走 src/decimal.mjs：那是自己写的往返，一位不差地对过宿主的成文与解析。
// 进制那一支是整数，自己逐字符累加 —— 它是整数的意思，不是浮点的意思。
export const 解析 = (文, 进制 = 0) => {
  const 净 = String(文).replace(/_/g, "");
  if (进制) {
    if (!净) return NaN;
    let 值 = 0n;
    for (const ch of 净) {
      const d = 数字值(ch);
      if (d < 0 || d >= 进制) return NaN;
      值 = 值 * BigInt(进制) + BigInt(d);
    }
    return Number(值);
  }
  const 位们 = 十进.解析(净);
  return 位们 === null ? NaN : 由位(位们);
};

const 数字值 = (ch) => {
  const c = ch.codePointAt(0);
  if (c >= 48 && c <= 57) return c - 48;        // 0 到 9
  if (c >= 97 && c <= 122) return c - 87;       // a 到 z
  if (c >= 65 && c <= 90) return c - 55;        // A 到 Z
  return -1;
};

// 数 → 文本。走 src/decimal.mjs：最短的、还能读回来的那一串。
// 位数与排版都已经与宿主的 String() 逐条对过，所以这一句换过之后行为不变。
export const 成文 = (n) => 十进.成文(位(n));

// 算术：两条实现，同一条路。
//
//   宿主的  一行一个运算，直接落在 JS 的双精度上。
//   f64     走 src/f64.mjs：加、减、乘、除、余、比全用自己的整数算，值的表示
//           仍是那六十四个位（借 bits 进出），而运算本身一页都不借。
//
// 默认是宿主那一条。理由是一个量出来的数：自己的算术比宿主的慢约三百倍
// （二十万次加乘：零点九毫秒对二百六十五毫秒）。自举那一层跑一次求值要做
// 几十万次算术，三百倍就是「不能用了」。所以这一格做的是「能换」，不是「换掉了」。
//
// 换的同一条路上还有一件事要记住：f64.比 对 NaN 交回 null（不可比），而这一层
// 现在的行为是把不可比压成 0。见 design/SCALARS.txt「还没量的」里那一条 ——
// 换实现的时候要把它一起定下来，眼下先保持旧行为，不顺手改。
import * as 浮点 from "./f64.mjs";

// 自家算术是默认（2026-10-25）。它慢一点 —— 量过：整数 1.5 倍、浮点 4.1 倍，
// 最重的一套（curve 那 26 项，含 Ed25519）3.1 倍 —— 换来的是「算术与比较只有一处实现，
// 三条执行路都不再借宿主的裸运算」。HMYR_ARITH=0 退回宿主那一条，用来对照与排查。
let 走自家 = process.env.HMYR_ARITH !== "0";
export const 用自家算术 = (开 = true) => { 走自家 = 开 === true; };
export const 在用自家算术 = () => 走自家;

const 自家加 = (a, b) => 由位(浮点.加(位(a), 位(b)));
const 自家减 = (a, b) => 由位(浮点.减(位(a), 位(b)));
const 自家乘 = (a, b) => 由位(浮点.乘(位(a), 位(b)));
const 自家除 = (a, b) => 由位(浮点.除(位(a), 位(b)));
const 自家余 = (a, b) => 由位(浮点.余(位(a), 位(b)));
const 自家反 = (a) => 由位(浮点.翻符号(位(a)));
const 自家是零 = (n) => 浮点.拆(位(n)).种 === "零";
const 自家同 = (a, b) => 浮点.同(位(a), 位(b));
const 自家比 = (a, b) => {
  const r = 浮点.比(位(a), 位(b));
  return r === null ? 0 : r;      // 不可比压成 0：这是旧行为，换实现时要一起定
};

// 整数快路。自举里绝大多数算术是整数：下标、长度、计数器、循环变量。
// 双精度能精确表示到 2 的 53 次方，所以在这一段里的整数加减乘与比较，
// 用宿主的整数算就是精确的 —— 它与 f64 那条路给出的位模式完全相同，
// 而这一步省掉的是 BigInt 的拆与装。
//
// 它借的是「整数」而不是「浮点」：安全整数范围内的加减乘没有舍入，
// 借不借宿主的加法在这件事上没有差别。而一旦出了这个范围，
// 立刻落回 f64 那一条 —— 那里才有舍入要管。
const 快整数 = (x) => Number.isSafeInteger(x);
const 快加 = (a, b) => { const s = a + b; return Number.isSafeInteger(s) ? s : 自家加(a, b); };
const 快减 = (a, b) => { const s = a - b; return Number.isSafeInteger(s) ? s : 自家减(a, b); };
const 快乘 = (a, b) => { const p = a * b; return Number.isSafeInteger(p) ? p : 自家乘(a, b); };
// 往小的那一头取整。切片与码点用它，而下标不用它 —— 下标不取整是一个刻意的洞，
// 见 design/SCALARS.txt「还没量的」那一节。
//
// 宿主的 floor 与自己的那一份各一条：自家那条在 src/f64.mjs，它从指数与尾数上
// 把整数部分读出来，不借宿主的取整。默认仍走宿主那一行 —— 与算术的其他几行同一个安排。
export const 下整 = (n) => (走自家 ? 由位(浮点.下整(位(n))) : Math.floor(n));

export const 加 = (a, b) => (走自家 ? (快整数(a) && 快整数(b) ? 快加(a, b) : 自家加(a, b)) : a + b);
export const 减 = (a, b) => (走自家 ? (快整数(a) && 快整数(b) ? 快减(a, b) : 自家减(a, b)) : a - b);
export const 乘 = (a, b) => (走自家 ? (快整数(a) && 快整数(b) ? 快乘(a, b) : 自家乘(a, b)) : a * b);
export const 除 = (a, b) => (走自家 ? 自家除(a, b) : a / b);
export const 余 = (a, b) => (走自家 ? 自家余(a, b) : a % b);
export const 反 = (a) => (走自家 ? 自家反(a) : -a);

// 零的判定要单独有名字：除法与取余都要它，而「等于零」在这里不是相等 ——
// 相等是跨类型的那一条规则（见执行器的 相等），这一条只问一个数是不是零。
// 安全整数里 0 与 -0 都等于零，所以这一条不必走 f64。
export const 是零 = (n) => (走自家 ? (快整数(n) ? n === 0 : 自家是零(n)) : n === 0);

// 两个数相等。负数零与正零相等（那正是 IEEE 的规矩），NaN 与任何东西都不等。
export const 同 = (a, b) => (走自家 ? (快整数(a) && 快整数(b) ? a === b : 自家同(a, b)) : a === b);

// 两个数能不能比。NaN 与任何东西都不行，而这一点影响的是「四条比较」里的两条：
// 「比」把不可比压成 0（等于），于是 <= 与 >= 在 NaN 上会成立，< 与 > 不会。
// 判定与「数的意思只在一处」同一条理由 —— 三个执行器与 C 那台共用这一个规矩，
// 不再各自写一遍 a !== a。
export const 有序 = (a, b) => a === a && b === b;

// 比较：-1 / 0 / 1。相等不算出错，所以它总是在这三个里交回一个。
export const 比 = (a, b) => (走自家
  ? (快整数(a) && 快整数(b) ? (a < b ? -1 : a > b ? 1 : 0) : 自家比(a, b))
  : a < b ? -1 : a > b ? 1 : 0);

// 算术那一组内置要落在这里，而不是让内置表直接写 Math.abs / Math.trunc。
// 理由与上面几行相同：数的意思收在一处，换实现只有一个落点。
// 它们都是「一个有符号的零也照 IEEE 走」的形状 —— 绝对值的负数零仍是零。
export const 绝对 = (n) => (n < 0 ? -n : n);
export const 截断 = (n) => (n < 0 ? -Math.floor(-n) : Math.floor(n));
export const 最小 = (们) => {
  let 佳 = 们[0];
  for (const x of 们) if (x < 佳) 佳 = x;
  return 佳;
};
export const 最大 = (们) => {
  let 佳 = 们[0];
  for (const x of 们) if (x > 佳) 佳 = x;
  return 佳;
};

