// 文本：字符串的码元操作，只有一个定义处。
//
// 与 src/numbers.mjs 同一种做法：这一份没有把字符串换掉（它仍是宿主的 UTF-16 串），
// 它把「一个字是什么、一个字有多长、怎么切、怎么比」收成一处。执行器与内置表
// 都读它，于是换掉字符串的时候只有一个落点。
//
// 三条语义是这门语言的，不是宿主的默认值，所以它们写在这里而不是留在调用处：
//
//   长度按 UTF-16 码元数，不按字符数 —— 一个表情是二。按字符数更合人的直觉，
//   而它会让每一处下标、切片与长度的含义同时改变。
//   下标取一个码元 —— 于是取到半个代理对是允许的，那正是码元的定义。
//   比较按码元序。
//
// design/SCALARS.txt 第二节量出来的那些行为，就是这一层要保住的东西。

export const 是串 = (v) => typeof v === "string";

// 一、长度：码元数。
export const 长 = (s) => s.length;

// 二、界内判定与取一个码元。取不到的时候交回 undefined —— 那是「没有这个码元」，
// 而报哪一个编号是执行器的事，不在这一层编（与 numbers 收 交回 null 同一个立场）。
export const 在界内 = (s, i) => i >= 0 && i < s.length;
export const 元 = (s, i) => s[i];

// 三、切片。起止都在码元位置上，夹由调用处负责 —— 这里的立场是「交给我一段位置，
// 我给你那一段」，把负数与超界各自夹到哪一头，是内置表那一侧的规矩。
export const 切 = (s, 起, 止) => s.slice(起, 止);

// 拼接。
export const 拼 = (a, b) => a + b;

// 比较：按码元序，交回 -1 / 0 / 1。
export const 比 = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// 码点 → 一个码元或一对代理。这是数与文本之间的一道桥，也是 chr 的全部。
export const 码点 = (n) => String.fromCodePoint(n);

