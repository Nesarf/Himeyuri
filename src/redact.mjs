// 脱敏：诊断里要不要说出路径。
//
// 一件事要说清：这门语言的编号是契约，消息是给人看的。脱敏改的只是消息里的那一截 —
// 编号一个都不动，于是「靠编号分辨是什么错」这件事不受影响。
//
// 为什么要有它：一个工具报告「读不到 /home/someone/项目/密钥.txt」，那份日志现在带着
// 那个人机器的布局。默认说出来是因为多半在本地调试，而发出去的日志不该替人说出这些。
//
// 这一条是从 oak-barrels 学来的（它的协议第 8 节：诊断默认脱敏，识别是另一个开关）。
// 那一条比它看起来重要：指纹往往不在版本号里，在路径里。
//
// 范围刻意画小：只有「我们确知那是路径」的地方才换。消息里出现 URL、编号、普通词
// 都不该被这条规则碰到 —— 靠猜哪一段像路径，猜错一次就把一条真诊断毁了。

let 开 = false;

export const 设脱敏 = (v) => { 开 = v === true; };
export const 在用脱敏 = () => 开;

// 一个路径，或者一个占位符。名字叫「藏路径」是因为调用处读起来清楚：
// 消息里写 藏路径(路径)，读者立刻知道这里原本是什么。
export const 藏路径 = (p) => (开 ? "<path>" : p);

// 整条诊断：把引号里带着斜杠或反斜杠的那一截换成 <path>。
//
// 这一条与上面那条分工不同：上面是「我们确知那是路径」，用于内置自己拼的消息；
// 这一条是「别人拼的消息里带着路径」，用于启动器把 stderr 交出去之前。
// 后一条存在的理由是自举层：那条 no such file 是 HMYR 自己写的解释器拼的，
// 它不知道开关，所以只能在出门处替它遮一次。
//
// 正则刻意窄：只碰引号里、且含分隔符的串。编号、URL 里没有反斜杠而带斜杠的
// 引号串很少见 —— 真有的话被遮掉一次也比漏一条路径好，这是取舍，写在这里。
export const 脱线 = (文) => (开 ? 文.replace(/('[^']*[\\/][^']*'|"[^"]*[\\/][^"]*")/g, "'<path>'") : 文);
