// 文本层的两个实现，同一个接口。
//
// src/text.mjs 定义的是「一个字符串怎么算长短、怎么切、怎么比」，
// 而 src/units.mjs 把同一套规矩落在一块码元内存上。这一份把两者摆成同一个形状，
// 于是执行器可以带着「用哪一种底」跑，而不必在每个调用处写一遍分支。
//
// 接口（两边同形，返回值都是「语言的字符串值」）：
//
//   是串   这个值是不是字符串
//   长     码元数
//   在界内 下标在不在里头
//   元     取一个码元，交回一个字符串值（在码元那种底上，是只有一位的序列）
//   切     起止之间的那一段
//   拼     接起来
//   比     -1 / 0 / 1
//   码点   一个数变一个字符串值
//   成宿主 写成宿主串（输出与错误消息用 —— 那一头总要落回世界）
//   由宿主 从宿主串收进来（字面量、命令行参数、读文件用）
import * as 宿 from "./text.mjs";
import * as 码 from "./units.mjs";

// 宿主串那一层：它是默认的底，所以 成宿主 与 由宿主 都是恒等。
export const 宿主串层 = {
  名: "宿主串",
  是串: 宿.是串,
  长: 宿.长,
  在界内: 宿.在界内,
  元: (s, i) => 宿.元(s, i),
  切: 宿.切,
  拼: 宿.拼,
  比: 宿.比,
  码点: 宿.码点,
  成宿主: (s) => s,
  由宿主: (s) => s,
};

// 码元那一层：元 交回一位的序列，因为「取一个码元」得到的也是一个字符串值。
export const 码元串层 = {
  名: "码元序列",
  是串: 码.是码元序列,
  长: 码.长,
  在界内: 码.在界内,
  元: (a, i) => 码.码点(码.元(a, i)),
  切: 码.切,
  拼: 码.拼,
  比: 码.比,
  码点: 码.码点,
  成宿主: 码.成宿主,
  由宿主: 码.由宿主,
};

export const 按选项取 = (选项 = {}) => (选项.字符串用码元序列 === true ? 码元串层 : 宿主串层);

// 一个字面量或别处来的宿主串，落到选定的那一层上。
export const 收进来 = (层, s) => (层.名 === "宿主串" ? s : 层.由宿主(s));
